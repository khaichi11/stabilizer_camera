#!/usr/bin/env python3
"""Packs the web app (docs/) into firmware/D435_gimbal_ESP32C3/web_files.h, gzip-compressed, so the
ESP32 can serve it over WiFi. Run after changing anything in docs/:

    python3 tools/embed_web.py          # write the header
    python3 tools/embed_web.py --check  # fail if the header is out of date (used by CI)
"""
import gzip, sys, zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = ROOT / "firmware" / "D435_gimbal_ESP32C3" / "web_files.h"
FILES = [  # (served path, file in docs/, content type)
    ("/index.html", "index.html", "text/html; charset=utf-8"),
    ("/vendor/three.module.min.js", "vendor/three.module.min.js", "text/javascript"),
    ("/vendor/OrbitControls.js", "vendor/OrbitControls.js", "text/javascript"),
    ("/model/gimbal.bin", "model/gimbal.bin", "application/octet-stream"),
    ("/img/gimbal.webp", "img/gimbal.webp", "image/webp"),
    ("/img/icon.svg", "img/icon.svg", "image/svg+xml"),
    ("/img/icon-192.png", "img/icon-192.png", "image/png"),
    ("/manifest.webmanifest", "manifest.webmanifest", "application/manifest+json"),
    ("/skema_rangkaian.svg", "skema_rangkaian.svg", "image/svg+xml"),
]

def build():
    out = ["// Generated by tools/embed_web.py from docs/. Do not edit: change docs/ and run the script.",
           "#pragma once", "#include <stdint.h>",
           "struct WebFile { const char *path; const char *type; const char *etag; const uint8_t *data; uint32_t len; };"]
    table, total = [], 0
    for i, (path, src, ctype) in enumerate(FILES):
        raw = (DOCS / src).read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        etag = '"%08x"' % zlib.crc32(raw)
        out.append(f"// {src}: {len(raw)} bytes, gzip {len(gz)}")
        out.append(f"static const uint8_t WF{i}[] = {{")
        for k in range(0, len(gz), 40):
            out.append(",".join(str(b) for b in gz[k:k + 40]) + ",")
        out.append("};")
        table.append(f'  {{"{path}", "{ctype}", "\\{etag[:-1]}\\"", WF{i}, {len(gz)}}},')
    out.append("static const WebFile WEB_FILES[] = {")
    out += table
    out.append("};")
    out.append(f"static const int WEB_FILES_N = {len(FILES)};  // {total} bytes in flash")
    return "\n".join(out) + "\n", total

def check():
    """Compares what the header holds (unzipped) with docs/. Not the gzip bytes: another zlib build
    may compress the same file slightly differently."""
    import re
    if not OUT.exists():
        return "web_files.h is missing"
    text = OUT.read_text()
    arrays = {int(m.group(1)): bytes(int(x) for x in m.group(2).replace("\n", "").split(",") if x.strip())
              for m in re.finditer(r"static const uint8_t WF(\d+)\[\] = \{(.*?)\};", text, re.S)}
    rows = re.findall(r'\{"([^"]+)", "([^"]+)", "\\"([0-9a-f]+)\\"", WF(\d+), (\d+)\}', text)
    if len(rows) != len(FILES):
        return "the file list changed"
    for (path, src, ctype), (hp, ht, he, hi, hl) in zip(FILES, rows):
        raw = (DOCS / src).read_bytes()
        data = arrays.get(int(hi), b"")
        if (path, ctype) != (hp, ht) or len(data) != int(hl) or he != "%08x" % zlib.crc32(raw):
            return f"{src} changed"
        if gzip.decompress(data) != raw:
            return f"{src} differs"
    return None

if __name__ == "__main__":
    if "--check" in sys.argv:
        why = check()
        if why:
            print(f"web_files.h is out of date ({why}): run python3 tools/embed_web.py"); sys.exit(1)
        print("web_files.h matches docs/"); sys.exit(0)
    text, total = build()
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(FILES)} files, {total} bytes gzip")
